#!/usr/bin/env node

/**
 * Script to automatically generate the MDX import registry
 * Run this whenever you add new lessons: npm run generate-mdx-registry
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import matter from 'gray-matter'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')

function discoverLessons() {
  const contentDir = path.join(projectRoot, 'content', 'lessons')
  const lessons = []

  if (!fs.existsSync(contentDir)) {
    console.error(`❌ Content directory not found: ${contentDir}`)
    process.exit(1)
  }

  // Read all chapter directories
  const chapters = fs.readdirSync(contentDir, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory() && !dirent.name.startsWith('.'))

  for (const chapter of chapters) {
    const chapterPath = path.join(contentDir, chapter.name)

    // Read all MDX files in the chapter directory
    const files = fs.readdirSync(chapterPath)
      .filter(file => file.endsWith('.mdx'))

    for (const file of files) {
      const fileName = file.replace('.mdx', '')

      // Create slug: for files named same as directory, use just directory name
      // Otherwise use directory/filename format
      const slug = fileName === chapter.name
        ? chapter.name
        : `${chapter.name}/${fileName}`

      const importPath = `@/content/lessons/${chapter.name}/${fileName}.mdx`

      // Read and parse frontmatter from the MDX file
      const filePath = path.join(chapterPath, file)
      const fileContents = fs.readFileSync(filePath, 'utf8')
      const { data: frontmatter } = matter(fileContents)

      lessons.push({ slug, importPath, frontmatter })
    }
  }

  return lessons
}

function generateRegistry() {
  console.log('🔍 Discovering lessons...')
  const lessons = discoverLessons()

  console.log(`✅ Found ${lessons.length} lessons\n`)

  // Generate the TypeScript code
  const registryCode = `// This file is auto-generated by scripts/generate-mdx-registry.mjs
// Do not edit manually - run: npm run generate-mdx-registry

/**
 * Static import registry for all MDX lessons
 * Next.js requires explicit import statements for static analysis
 * This registry maps slugs to their import functions
 */
export const mdxImportRegistry: Record<string, () => Promise<any>> = {
${lessons.map(({ slug, importPath }) => 
  `  "${slug}": () => import("${importPath}"),`
).join('\n')}
}

/**
 * Get all registered lesson slugs
 */
export function getRegisteredSlugs(): string[] {
  return Object.keys(mdxImportRegistry)
}

export interface LessonRegistryItem {
  slug: string;
  import: () => Promise<any>;
  frontmatter: Record<string, any>;
  chapter: string;
}

/**
 * Full registry with lesson metadata
 * Includes frontmatter and chapter info for each lesson
 */
export const mdxRegistry: LessonRegistryItem[] = [
${lessons.map(({ slug, importPath, frontmatter }) => {
  const chapterSlug = slug.split('/')[0]
  return `  {
    slug: "${slug}",
    import: () => import("${importPath}"),
    frontmatter: ${JSON.stringify(frontmatter, null, 6).split('\n').join('\n    ')},
    chapter: "${chapterSlug}"
  }`
}).join(',\n')}
]

/**
 * Get all chapters with their lessons
 */
export function getChaptersWithLessons() {
  const chapters: Record<string, LessonRegistryItem[]> = {}
  mdxRegistry.forEach(item => {
    if (!chapters[item.chapter]) chapters[item.chapter] = []
    chapters[item.chapter].push(item)
  })
  return chapters
}

/**
 * Get lesson by slug
 */
export function getLessonBySlug(slug: string): LessonRegistryItem | undefined {
  return mdxRegistry.find(item => item.slug === slug)
}
`

  // Write to lib/mdx-registry.ts
  const outputPath = path.join(projectRoot, 'lib', 'mdx-registry.ts')
  fs.writeFileSync(outputPath, registryCode, 'utf8')

  console.log(`📝 Generated registry at: ${outputPath}`)
  console.log('\nRegistered lessons:')
  lessons.forEach(({ slug }) => {
    console.log(`  ✓ ${slug}`)
  })

  console.log('\n✅ MDX registry generated successfully!')
  console.log('💡 Import it in mdx-loader.ts: import { mdxImportRegistry } from "./mdx-registry"')
}

// Run the generator
try {
  generateRegistry()
} catch (error) {
  console.error('❌ Failed to generate registry:', error)
  process.exit(1)
}
