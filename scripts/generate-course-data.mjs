#!/usr/bin/env node

/**
 * Script to automatically generate course-data.ts from filesystem
 * Discovers lessons and updates the course structure
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import matter from 'gray-matter'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')

// Chapter metadata - manually maintained
const chapterMetadata = {
  'introduction': {
    number: 1,
    title: 'Introduction',
    description: 'Dive into the course materials',
    icon: 'book'
  },
  'getting-started': {
    number: 2,
    title: 'Getting Started',
    description: 'Learn how to create a Webiny application and run your local development server.',
    icon: 'rocket'
  },
  'website-builder': {
    number: 3,
    title: 'Website Builder',
    description: "Learn how to build pages with Webiny's visual website builder.",
    icon: 'palette'
  },
  'headless-cms': {
    number: 4,
    title: 'Headless CMS',
    description: "Learn how to use Webiny's Headless CMS to manage your content.",
    icon: 'edit'
  },
  'serverless': {
    number: 5,
    title: 'Serverless',
    description: 'Learn about the serverless architecture that powers Webiny.',
    icon: 'cloud'
  },
  'best-practices': {
    number: 6,
    title: 'Best Practices',
    description: 'Learn best practices for building production-ready Webiny applications.',
    icon: 'star'
  }
}

function discoverLessonsWithMetadata() {
  const contentDir = path.join(projectRoot, 'content', 'lessons')
  const chapters = {}

  if (!fs.existsSync(contentDir)) {
    console.error(`❌ Content directory not found: ${contentDir}`)
    process.exit(1)
  }

  // Read all chapter directories
  const chapterDirs = fs.readdirSync(contentDir, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory() && !dirent.name.startsWith('.'))
    .sort((a, b) => {
      const aNum = chapterMetadata[a.name]?.number || 999
      const bNum = chapterMetadata[b.name]?.number || 999
      return aNum - bNum
    })

  for (const chapterDir of chapterDirs) {
    const chapterName = chapterDir.name
    const chapterPath = path.join(contentDir, chapterName)
    const metadata = chapterMetadata[chapterName] || {
      number: 999,
      title: chapterName.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' '),
      description: `Learn about ${chapterName.replace(/-/g, ' ')}`,
      icon: 'book'
    }

    // Read all MDX files in the chapter directory
    const files = fs.readdirSync(chapterPath)
      .filter(file => file.endsWith('.mdx'))
      .sort()

    const lessons = []

    for (const file of files) {
      const fileName = file.replace('.mdx', '')
      const filePath = path.join(chapterPath, file)

      // Read frontmatter for lesson metadata
      let title = fileName.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')

      try {
        const fileContent = fs.readFileSync(filePath, 'utf8')
        const { data } = matter(fileContent)
        if (data.title) {
          title = data.title
        }
      } catch (error) {
        console.warn(`⚠️  Could not read frontmatter from ${file}:`, error.message)
      }

      // Create slug
      const slug = fileName === chapterName
        ? chapterName
        : `${chapterName}/${fileName}`

      lessons.push({
        id: fileName,
        title,
        slug
      })
    }

    chapters[chapterName] = {
      id: chapterName,
      ...metadata,
      lessons
    }
  }

  return chapters
}

function generateCourseData() {
  console.log('🔍 Discovering lessons and generating course data...')

  const chapters = discoverLessonsWithMetadata()
  const chapterArray = Object.values(chapters)

  console.log(`✅ Found ${chapterArray.length} chapters with ${chapterArray.reduce((sum, ch) => sum + ch.lessons.length, 0)} lessons\n`)

  // Generate the TypeScript code
  const courseDataCode = `// This file is partially auto-generated by scripts/generate-course-data.mjs
// Chapter metadata is manually maintained, but lessons are auto-discovered
// Run: npm run generate-course-data

import { ChapterIconType } from "./chapter-icons"

export interface Lesson {
  id: string
  title: string
  slug: string
}

export interface Chapter {
  id: string
  number: number
  title: string
  description: string
  icon: ChapterIconType
  lessons: Lesson[]
}

export interface Course {
  id: string
  title: string
  description: string
  chapters: Chapter[]
}

export const courseData: Course = {
  id: "learn-webiny",
  title: "Learn Webiny",
  description:
    "Go from beginner to expert by learning the foundations of Webiny and building a fully functional serverless application that uses all the latest features.",
  chapters: ${JSON.stringify(chapterArray, null, 4).replace(/"([^"]+)":/g, '$1:')},
}

export function getAllLessons(): Array<{ chapterId: string; lessonId: string; slug: string }> {
  const lessons: Array<{ chapterId: string; lessonId: string; slug: string }> = []

  courseData.chapters.forEach((chapter) => {
    chapter.lessons.forEach((lesson) => {
      lessons.push({
        chapterId: chapter.id,
        lessonId: lesson.id,
        slug: lesson.slug,
      })
    })
  })

  return lessons
}

export function getNextLesson(currentSlug: string): { chapterId: string; lessonId: string; slug: string } | null {
  const allLessons = getAllLessons()
  const currentIndex = allLessons.findIndex((l) => l.slug === currentSlug)

  if (currentIndex === -1 || currentIndex === allLessons.length - 1) {
    return null
  }

  return allLessons[currentIndex + 1]
}

export function getPreviousLesson(currentSlug: string): { chapterId: string; lessonId: string; slug: string } | null {
  const allLessons = getAllLessons()
  const currentIndex = allLessons.findIndex((l) => l.slug === currentSlug)

  if (currentIndex <= 0) {
    return null
  }

  return allLessons[currentIndex - 1]
}

export function getLessonBySlug(slug: string) {
  for (const chapter of courseData.chapters) {
    const lesson = chapter.lessons.find((l) => l.slug === slug)
    if (lesson) {
      return { chapter, lesson }
    }
  }
  return null
}

export function isLastLessonInChapter(slug: string): boolean {
  const result = getLessonBySlug(slug)
  if (!result) return false

  const { chapter, lesson } = result
  const lessonIndex = chapter.lessons.findIndex((l) => l.id === lesson.id)
  return lessonIndex === chapter.lessons.length - 1
}

export function getNextChapter(currentSlug: string): Chapter | null {
  const result = getLessonBySlug(currentSlug)
  if (!result) return null

  const { chapter } = result
  const chapterIndex = courseData.chapters.findIndex((c) => c.id === chapter.id)

  if (chapterIndex === -1 || chapterIndex === courseData.chapters.length - 1) {
    return null
  }

  return courseData.chapters[chapterIndex + 1]
}

export function getChapterById(chapterId: string): Chapter | null {
  return courseData.chapters.find((c) => c.id === chapterId) || null
}

export function getLessonNumber(slug: string): number {
  const allLessons = getAllLessons()
  const index = allLessons.findIndex((l) => l.slug === slug)
  return index !== -1 ? index + 1 : 0
}

export function getLessonNumberInChapter(slug: string): number {
  const result = getLessonBySlug(slug)
  if (!result) return 0

  const { chapter, lesson } = result
  const lessonIndex = chapter.lessons.findIndex((l) => l.id === lesson.id)
  return lessonIndex !== -1 ? lessonIndex + 1 : 0
}
`

  // Write to lib/course-data.ts
  const outputPath = path.join(projectRoot, 'lib', 'course-data.ts')
  fs.writeFileSync(outputPath, courseDataCode, 'utf8')

  console.log(`📝 Generated course data at: ${outputPath}`)
  console.log('\nChapters and lessons:')
  chapterArray.forEach(chapter => {
    console.log(`  ${chapter.number}. ${chapter.title} (${chapter.lessons.length} lessons)`)
    chapter.lessons.forEach(lesson => {
      console.log(`     - ${lesson.title} [${lesson.slug}]`)
    })
  })

  console.log('\n✅ Course data generated successfully!')
}

// Run the generator
try {
  generateCourseData()
} catch (error) {
  console.error('❌ Failed to generate course data:', error)
  process.exit(1)
}

